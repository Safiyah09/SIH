export type DictKey = keyof (typeof dictionary)['en']

export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>) {
  const text: string = dictionary[lang][key] ?? dictionary.en[key]
  if (!vars) return text
  return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ''))
}

export const LANG_COOKIE = 'goa-heritage-lang'

